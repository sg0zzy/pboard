export async function buildSignedSignal(
  signer: SigningInput,
  context: EnvelopeContext,
  target: { deviceKeyId: string; sessionId: string },
  signal: unknown,
  sequence: number,
  lifetimeMs = SIGNAL_LIFETIME_MS
): Promise<SignedSignal> {
  deviceRoleOrThrow(context.manifest, signer.deviceKeyId);
  const payload: SignedSignalPayload = {
    protocol: PROTOCOL_VERSION,
    boardId: context.boardId,
    collection: context.collection,
    manifestHash: manifestHash(context.manifest),
    epoch: context.manifest.epoch,
    fromDeviceKeyId: signer.deviceKeyId,
    fromSessionId: context.ownSessionId,
    toDeviceKeyId: target.deviceKeyId,
    toSessionId: target.sessionId,
    signalId: crypto.randomUUID(),
    issuedAt: context.now,
    expiresAt: context.now + lifetimeMs,
    sequence,
    signal
  };
  const signature = await signBytes(await importSigningInput(signer), signedBytes(DOMAIN_SIGNAL, deepJson(payload)));
  return { payload, signature };
}

/**
 * The only `unknown`-typed field in a signed payload is the inner simple-peer
 * signal, already constrained by the transport to plain JSON values (SDP strings
 * or candidate objects). Canonicalization requires `Json`, and non-JSON inner
 * values (functions, cycles) must be rejected rather than silently coerced.
 */
function deepJson(value: SignedSignalPayload): JsonPayload {
  return JSON.parse(JSON.stringify(value, (_key, entry) => {
    if (entry === undefined) throw new Error("Cannot sign a payload containing `undefined`");
    if (typeof entry === "bigint") throw new Error("Cannot sign a payload containing `bigint`");
    return entry;
  })) as JsonPayload;
}

type JsonPayload = Parameters<typeof signedBytes>[1];

export type SignalCheck = {
  manifest: BoardPermissionManifest;
  expected: { boardId: string; collection: ProtocolCollection; manifestHash: string; ownDeviceKeyId: string; ownSessionId: string };
  now: number;
};

/** Per-remote-session replay cache: signal ids already accepted. */
export type ReplayCache = {
  /** signalId -> issuedAt, bounded per remote session. */
  accepted: Map<string, Map<string, number>>;
};

export function createReplayCache(): ReplayCache {
  return { accepted: new Map() };
}

/**
 * Verifies an inbound signed signal fully before its SDP reaches simple-peer:
 * manifest binding, expiry, device membership, session addressing and replay.
 * Returns the inner simple-peer signal.
 */
export async function verifySignedSignal(
  signed: unknown,
  check: SignalCheck,
  replay: ReplayCache
): Promise<unknown> {
  const envelope = signed as Partial<SignedSignal> | null;
  const payload = envelope?.payload;
  if (!payload || typeof payload !== "object") throw new Error("Signal payload is missing");
  if (payload.protocol !== PROTOCOL_VERSION) throw new Error("Signal protocol version is unsupported");
  if (payload.boardId !== check.expected.boardId || payload.collection !== check.expected.collection) throw new Error("Signal is bound to another room");
  if (payload.epoch !== check.manifest.epoch) throw new Error("Signal epoch does not match manifest");
  if (payload.manifestHash !== check.expected.manifestHash) throw new Error("Signal references an unverified manifest");
  if (payload.toDeviceKeyId !== check.expected.ownDeviceKeyId || payload.toSessionId !== check.expected.ownSessionId) throw new Error("Signal is addressed to another session");
  if (!Number.isSafeInteger(payload.expiresAt) || payload.expiresAt < check.now) throw new Error("Signal has expired");
  if (payload.expiresAt - payload.issuedAt > SIGNAL_LIFETIME_MS + 30_000) throw new Error("Signal lifetime exceeds protocol limits");
  if (!Number.isSafeInteger(payload.sequence) || (payload.sequence as number) < 0) throw new Error("Signal sequence is invalid");
  const device = check.manifest.devices.find((entry) => entry.deviceKeyId === payload.fromDeviceKeyId);
  if (!device) throw new Error("Signal key is not in the verified manifest");
  // Re-canonicalize the untrusted payload through strict parsing: non-JSON values
  // and duplicate members never reach signature verification.
  const trusted = parseStrictJson(JSON.stringify(payload)) as unknown as Parameters<typeof signedBytes>[1];
  const ok = await verifyBytes(device.publicKey, String(envelope.signature ?? ""), signedBytes(DOMAIN_SIGNAL, trusted));
  if (!ok) throw new Error("Signal signature verification failed");
  const seen = replay.accepted.get(payload.fromSessionId) ?? new Map<string, number>();
  if (seen.has(payload.signalId)) throw new Error("Signal replay rejected");
  seen.set(payload.signalId, payload.issuedAt);
  if (seen.size > MAX_REPLAY_CACHE_PER_SENDER) {
    // Evict the oldest half; bounded memory under flooding.
    const ordered = [...seen.entries()].sort((left, right) => left[1] - right[1]);
    for (const [id] of ordered.slice(0, Math.floor(MAX_REPLAY_CACHE_PER_SENDER / 2))) seen.delete(id);
  }
  replay.accepted.set(payload.fromSessionId, seen);
  return payload.signal;
}

