/**
 * Session binding, signed signaling envelopes and mutual proofs (protocol 2).
 *
 * Identity starts outside the shared signaling folder: a device holds a
 * fingerprint-pinned authority and a fresh manifest. Every presence record and
 * every signal is signed by its sender device and bound to the board, collection,
 * manifest hash, epoch, both session ids and a sequence number. Receivers keep
 * per-sender replay caches; expired, unknown-key, unbound or reused envelopes are
 * rejected. After DTLS connects, both sides exchange one bounded proof frame each,
 * signing a fresh challenge plus the ordered offer/answer transcript hash; only a
 * mutually proven session emits `connect$` and carries content.
 */
import {
  DOMAIN_PRESENCE, DOMAIN_SESSION_PROOF,
  DOMAIN_SIGNAL, parseStrictJson, PROTOCOL_VERSION, signedBytes
} from "./canonical";
import { signBytes, verifyBytes, importSigningKey, type DevicePublicKey } from "./keys";
import { manifestHash, manifestIsCurrent, roleForDevice, type BoardPermissionManifest, type ManifestRole } from "./manifest";

export type ProtocolCollection = "cards" | "projects" | "accountOrder";

/** A signed presence announcement carried in each peer's realtime record. */
export type SignedPresence = {
  payload: {
    protocol: typeof PROTOCOL_VERSION;
    boardId: string;
    collection: ProtocolCollection;
    manifestHash: string;
    epoch: number;
    deviceKeyId: string;
    sessionId: string;
    issuedAt: number;
    expiresAt: number;
  };
  signature: string;
};

/** A signed, session-bound signaling envelope carrying one simple-peer signal. */
export type SignedSignalPayload = {
  protocol: typeof PROTOCOL_VERSION;
  boardId: string;
  collection: ProtocolCollection;
  manifestHash: string;
  epoch: number;
  fromDeviceKeyId: string;
  fromSessionId: string;
  toDeviceKeyId: string;
  toSessionId: string;
  signalId: string;
  issuedAt: number;
  expiresAt: number;
  sequence: number;
  signal: unknown;
};

export type SignedSignal = { payload: SignedSignalPayload; signature: string };

/** The bounded post-DTLS authentication frame. */
export type SessionProofFrame = {
  payload: {
    protocol: typeof PROTOCOL_VERSION;
    boardId: string;
    collection: ProtocolCollection;
    fromDeviceKeyId: string;
    fromSessionId: string;
    toDeviceKeyId: string;
    toSessionId: string;
    manifestHash: string;
    /** The random challenge generated by the *receiving* side. */
    challenge: string;
    /** Hash of the ordered offer/answer transcript of this connection. */
    transcriptHash: string;
    issuedAt: number;
    expiresAt: number;
  };
  signature: string;
};

/** Immutable verified session context; never built from peer-controlled JSON. */
export type VerifiedSessionContext = {
  boardId: string;
  collection: ProtocolCollection;
  ownDeviceKeyId: string;
  remoteDeviceKeyId: string;
  remoteRole: ManifestRole;
  ownSessionId: string;
  remoteSessionId: string;
  manifestEpoch: number;
  manifestHash: string;
  transcriptHash: string;
  manifestExpiresAt: number;
};

export const PRESENCE_LIFETIME_MS = 120_000;
export const SIGNAL_LIFETIME_MS = 60_000;
export const PROOF_LIFETIME_MS = 30_000;
export const MAX_PENDING_SIGNALS_PER_SESSION = 32;
export const MAX_REPLAY_CACHE_PER_SENDER = 256;

export type SigningInput = {
  /** The sender's private JWK store record (see keys.ts). */
  privateJwk: JsonWebKey;
  deviceKeyId: string;
};

export type EnvelopeContext = {
  boardId: string;
  collection: ProtocolCollection;
  manifest: BoardPermissionManifest;
  ownSessionId: string;
  now: number;
};

function deviceRoleOrThrow(manifest: BoardPermissionManifest, deviceKeyId: string): ManifestRole {
  const role = roleForDevice(manifest, deviceKeyId);
  if (!role) throw new Error("Signing device is not authorized by the current manifest");
  return role;
}

// ---------------------------------------------------------------------------
// Presence
// ---------------------------------------------------------------------------

export async function buildPresence(
  signer: SigningInput,
  context: EnvelopeContext,
  lifetimeMs = PRESENCE_LIFETIME_MS
): Promise<SignedPresence> {
  deviceRoleOrThrow(context.manifest, signer.deviceKeyId);
  const payload = {
    protocol: PROTOCOL_VERSION,
    boardId: context.boardId,
    collection: context.collection,
    manifestHash: manifestHash(context.manifest),
    epoch: context.manifest.epoch,
    deviceKeyId: signer.deviceKeyId,
    sessionId: context.ownSessionId,
    issuedAt: context.now,
    expiresAt: context.now + lifetimeMs
  };
  const signature = await signBytes(await importSigningKey(signer.privateJwk), signedBytes(DOMAIN_PRESENCE, payload));
  return { payload, signature };
}

async function importSigningInput(signer: SigningInput): Promise<CryptoKey> {
  return importSigningKey(signer.privateJwk);
}

/**
 * Verifies a presence record against the manifest devices. `manifestHashOf`
 * must be the locally verified manifest's hash. Returns the sender's role.
 */
export async function verifyPresence(
  presence: unknown,
  manifest: BoardPermissionManifest,
  expected: { boardId: string; collection: ProtocolCollection; manifestHash: string; now: number }
): Promise<{ role: ManifestRole; deviceKeyId: string; sessionId: string }> {
  if (!manifestIsCurrent(manifest, expected.now)) throw new Error("Presence authorization manifest expired");
  const envelope = presence as Partial<SignedPresence> | null;
  const payload = envelope?.payload;
  if (!payload || typeof payload !== "object") throw new Error("Presence payload is missing");
  if (payload.protocol !== PROTOCOL_VERSION) throw new Error("Presence protocol version is unsupported");
  if (payload.boardId !== expected.boardId || payload.collection !== expected.collection) throw new Error("Presence is bound to another room");
  if (payload.epoch !== manifest.epoch || typeof payload.sessionId !== "string" || !payload.sessionId || payload.sessionId.length > 200 || payload.issuedAt > expected.now + 30_000) throw new Error("Presence epoch/session/time is invalid");
  if (payload.manifestHash !== expected.manifestHash) throw new Error("Presence references an unverified manifest");
  if (!Number.isSafeInteger(payload.expiresAt) || payload.expiresAt < expected.now || !Number.isSafeInteger(payload.issuedAt)) {
    throw new Error("Presence has expired or has invalid timestamps");
  }
  if (payload.expiresAt - payload.issuedAt > PRESENCE_LIFETIME_MS + 30_000) throw new Error("Presence lifetime exceeds protocol limits");
  const device = manifest.devices.find((entry) => entry.deviceKeyId === payload.deviceKeyId);
  if (!device) throw new Error("Presence key is not in the verified manifest");
  const ok = await verifyBytes(device.publicKey, String(envelope.signature ?? ""), signedBytes(DOMAIN_PRESENCE, payload));
  if (!ok) throw new Error("Presence signature verification failed");
  return { role: device.role, deviceKeyId: device.deviceKeyId, sessionId: String(payload.sessionId) };
}

