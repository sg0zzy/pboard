/** Builds our proof frame over the remote challenge, both ids and the transcript. */
export async function buildSessionProof(
  signer: SigningInput,
  context: {
    boardId: string;
    collection: ProtocolCollection;
    ownSessionId: string;
    remoteDeviceKeyId: string;
    remoteSessionId: string;
    manifest: BoardPermissionManifest;
  },
  challenge: string,
  transcriptHash: string,
  now: number
): Promise<SessionProofFrame> {
  deviceRoleOrThrow(context.manifest, signer.deviceKeyId);
  const payload = {
    protocol: PROTOCOL_VERSION,
    boardId: context.boardId,
    collection: context.collection,
    fromDeviceKeyId: signer.deviceKeyId,
    fromSessionId: context.ownSessionId,
    toDeviceKeyId: context.remoteDeviceKeyId,
    toSessionId: context.remoteSessionId,
    manifestHash: manifestHash(context.manifest),
    challenge,
    transcriptHash,
    issuedAt: now,
    expiresAt: now + PROOF_LIFETIME_MS
  };
  const signature = await signBytes(await importSigningInput(signer), signedBytes(DOMAIN_SESSION_PROOF, payload));
  return { payload, signature };
}

export async function verifySessionProof(
  frame: unknown,
  manifest: BoardPermissionManifest,
  expected: {
    boardId: string;
    collection: ProtocolCollection;
    ownDeviceKeyId: string;
    ownSessionId: string;
    manifestHash: string;
    issuedChallenge: string;
    transcriptHash: string;
    now: number;
  }
): Promise<{ deviceKeyId: string; role: ManifestRole }> {
  const envelope = frame as Partial<SessionProofFrame> | null;
  const payload = envelope?.payload;
  if (!payload || typeof payload !== "object") throw new Error("Proof payload is missing");
  if (payload.protocol !== PROTOCOL_VERSION) throw new Error("Proof protocol version is unsupported");
  if (payload.boardId !== expected.boardId || payload.collection !== expected.collection) throw new Error("Proof is bound to another room");
  if (payload.manifestHash !== expected.manifestHash) throw new Error("Proof references an unverified manifest");
  if (payload.toDeviceKeyId !== expected.ownDeviceKeyId || payload.toSessionId !== expected.ownSessionId) throw new Error("Proof is addressed to another session");
  if (payload.challenge !== expected.issuedChallenge) throw new Error("Proof does not answer our challenge");
  if (payload.transcriptHash !== expected.transcriptHash) throw new Error("Proof is bound to a different connection transcript");
  if (!Number.isSafeInteger(payload.expiresAt) || payload.expiresAt < expected.now) throw new Error("Proof has expired");
  const device = manifest.devices.find((entry) => entry.deviceKeyId === payload.fromDeviceKeyId);
  if (!device) throw new Error("Proof key is not in the verified manifest");
  const ok = await verifyBytes(device.publicKey, String(envelope.signature ?? ""), signedBytes(DOMAIN_SESSION_PROOF, payload));
  if (!ok) throw new Error("Proof signature verification failed");
  return { deviceKeyId: device.deviceKeyId, role: device.role };
}